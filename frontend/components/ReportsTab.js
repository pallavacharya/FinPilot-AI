import React, { useState, useEffect } from "react";
import { getReports, getReportById, generateReport, getAgentActions } from "../lib/api";
import {
  IconReport,
  IconDownload,
  IconX,
  IconRefresh,
} from "./icons";

function formatReportDate(isoString) {
  if (!isoString) return "";
  try {
    const d = new Date(isoString);
    return d.toLocaleString("en-US", {
      month: "short",
      day: "numeric",
      year: "numeric",
      hour: "numeric",
      minute: "2-digit",
    });
  } catch (e) {
    return isoString;
  }
}

export default function ReportsTab({ onOpenApproval }) {
  const [reports, setReports] = useState([]);
  const [loading, setLoading] = useState(true);
  const [filter, setFilter] = useState("all"); // 'all' | 'fraud' | 'sales'
  const [previewReport, setPreviewReport] = useState(null);
  const [previewLoading, setPreviewLoading] = useState(false);
  const [generating, setGenerating] = useState(false);
  const [actionsMap, setActionsMap] = useState({});

  function loadReports() {
    setLoading(true);
    Promise.all([
      getReports(null, 100).catch(() => ({ reports: [] })),
      getAgentActions().catch(() => ({ actions: [] })),
    ]).then(([rData, aData]) => {
      setReports(rData.reports || []);
      const aMap = {};
      (aData.actions || []).forEach((a) => {
        if (a.report_id) {
          aMap[a.report_id] = a;
        }
      });
      setActionsMap(aMap);
      setLoading(false);
    });
  }

  useEffect(() => {
    loadReports();
  }, []);

  async function handleOpenPreview(reportSummary) {
    setPreviewLoading(true);
    setPreviewReport(reportSummary);
    try {
      const full = await getReportById(reportSummary.id);
      setPreviewReport(full.report);
    } catch (e) {
      console.error("Failed to load report HTML", e);
    } finally {
      setPreviewLoading(false);
    }
  }

  function handleDownloadHtml(rep) {
    if (!rep?.html) return;
    const blob = new Blob([rep.html], { type: "text/html;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `${rep.id || "report"}.html`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }

  async function handleGenerate(kind, scope = "newest") {
    setGenerating(true);
    try {
      const res = await generateReport(kind, scope);
      loadReports();
      if (res.action && onOpenApproval) {
        onOpenApproval(res.action);
      }
    } catch (err) {
      alert(err.message || "Failed to generate report.");
    } finally {
      setGenerating(false);
    }
  }

  const filtered = reports.filter((r) => {
    if (filter === "fraud") return r.kind === "fraud";
    if (filter === "sales") return r.kind === "sales";
    return true;
  });

  function getStatusChip(status) {
    switch (status) {
      case "sent":
        return (
          <span className="status-pill pill-norm">
            SENT LIVE
          </span>
        );
      case "dry_run_saved":
        return (
          <span
            className="status-pill"
            style={{
              background: "rgba(62,207,142,0.1)",
              color: "var(--accent)",
              border: "1px solid rgba(62,207,142,0.3)",
            }}
          >
            DRY RUN SAVED
          </span>
        );
      case "failed":
        return (
          <span className="status-pill pill-susp">
            FAILED
          </span>
        );
      case "rejected":
        return (
          <span
            className="status-pill"
            style={{
              background: "rgba(138,147,166,0.15)",
              color: "var(--muted)",
              border: "1px solid var(--border)",
            }}
          >
            REJECTED
          </span>
        );
      case "draft":
      default:
        return (
          <span
            className="status-pill"
            style={{
              background: "rgba(74,144,226,0.12)",
              color: "#6ba4ec",
              border: "1px solid rgba(74,144,226,0.3)",
            }}
          >
            DRAFT PENDING
          </span>
        );
    }
  }

  return (
    <div>
      {/* Top Header */}
      <div className="topbar">
        <div>
          <h2>Deterministic Reports</h2>
          <div className="sub">Snapshot reports generated by rule-based agent loop</div>
        </div>
        <div style={{ display: "flex", gap: "10px", flexWrap: "wrap" }}>
          <button
            type="button"
            className="btn"
            onClick={() => handleGenerate("sales")}
            disabled={generating}
            style={{ fontSize: "12.5px", padding: "8px 14px" }}
          >
            {generating ? "Generating..." : "+ Generate Sales Outlook"}
          </button>
          <button
            type="button"
            className="btn primary"
            onClick={() => handleGenerate("fraud", "newest")}
            disabled={generating}
            style={{ width: "auto", fontSize: "12.5px", padding: "8px 14px" }}
          >
            {generating ? "Generating..." : "+ Generate Fraud Report"}
          </button>
        </div>
      </div>

      {/* Filter Tabs */}
      <div style={{ display: "flex", gap: "8px", marginBottom: "18px" }}>
        <button
          type="button"
          className={`btn ${filter === "all" ? "primary" : ""}`}
          onClick={() => setFilter("all")}
          style={{ padding: "6px 14px", fontSize: "12.5px", width: "auto" }}
        >
          All Reports ({reports.length})
        </button>
        <button
          type="button"
          className={`btn ${filter === "fraud" ? "primary" : ""}`}
          onClick={() => setFilter("fraud")}
          style={{ padding: "6px 14px", fontSize: "12.5px", width: "auto" }}
        >
          Fraud Alerts ({reports.filter((r) => r.kind === "fraud").length})
        </button>
        <button
          type="button"
          className={`btn ${filter === "sales" ? "primary" : ""}`}
          onClick={() => setFilter("sales")}
          style={{ padding: "6px 14px", fontSize: "12.5px", width: "auto" }}
        >
          Sales Outlook ({reports.filter((r) => r.kind === "sales").length})
        </button>
      </div>

      {/* Reports Table */}
      {loading ? (
        <div className="loading" style={{ padding: "40px", textAlign: "center" }}>
          Loading reports snapshot archive...
        </div>
      ) : filtered.length === 0 ? (
        <div className="card fraud-empty-card" style={{ padding: "60px 20px" }}>
          <div className="empty-icon-box">
            <IconReport size={28} />
          </div>
          <h3 style={{ margin: "0 0 8px 0", fontSize: "16px", color: "var(--text)" }}>
            No reports found
          </h3>
          <p className="empty-subtext">
            Upload a fraud CSV or click "Generate Sales Outlook" above to compile a deterministic report snapshot.
          </p>
        </div>
      ) : (
        <div className="card" style={{ padding: 0, overflow: "hidden", border: "1px solid var(--border)" }}>
          <div className="table-responsive">
            <table style={{ width: "100%", borderCollapse: "collapse", textAlign: "left", fontSize: "13px" }}>
              <thead>
                <tr style={{ background: "var(--panel-2)", borderBottom: "1px solid var(--border)", color: "var(--faint)" }}>
                  <th style={{ padding: "12px 16px", fontWeight: 600 }}>Type</th>
                  <th style={{ padding: "12px 16px", fontWeight: 600 }}>Subject</th>
                  <th style={{ padding: "12px 16px", fontWeight: 600 }}>Status</th>
                  <th style={{ padding: "12px 16px", fontWeight: 600 }}>Created</th>
                  <th style={{ padding: "12px 16px", fontWeight: 600 }}>Recipient</th>
                  <th style={{ padding: "12px 16px", fontWeight: 600, textAlign: "right" }}>Actions</th>
                </tr>
              </thead>
              <tbody>
                {filtered.map((rep) => {
                  const act = actionsMap[rep.id];
                  const canSend = act && (act.status === "pending_approval" || act.status === "failed");

                  return (
                    <tr
                      key={rep.id}
                      style={{ borderBottom: "1px solid var(--border)", transition: "background 0.12s" }}
                      className="tx-row"
                    >
                      <td style={{ padding: "12px 16px" }}>
                        <span
                          style={{
                            fontFamily: "var(--font-mono)",
                            fontSize: "11px",
                            fontWeight: 700,
                            padding: "3px 8px",
                            borderRadius: "4px",
                            background: rep.kind === "fraud" ? "rgba(229,89,95,0.12)" : "rgba(62,207,142,0.12)",
                            color: rep.kind === "fraud" ? "var(--red)" : "var(--accent)",
                            border: rep.kind === "fraud" ? "1px solid rgba(229,89,95,0.3)" : "1px solid rgba(62,207,142,0.3)",
                          }}
                        >
                          {rep.kind === "fraud" ? "FRAUD ALERT" : "SALES OUTLOOK"}
                        </span>
                      </td>

                      <td style={{ padding: "12px 16px", fontWeight: 600, color: "var(--text)" }}>
                        <div style={{ display: "flex", flexDirection: "column" }}>
                          <span>{rep.subject}</span>
                          <span style={{ fontSize: "11px", fontFamily: "var(--font-mono)", color: "var(--faint)", marginTop: "2px" }}>
                            ID: {rep.id}
                          </span>
                        </div>
                      </td>

                      <td style={{ padding: "12px 16px" }}>{getStatusChip(rep.status)}</td>

                      <td style={{ padding: "12px 16px", color: "var(--muted)", whiteSpace: "nowrap" }}>
                        {formatReportDate(rep.created_at)}
                      </td>

                      <td style={{ padding: "12px 16px", color: "var(--muted)", fontSize: "12px" }}>
                        {rep.sent_to || <span style={{ color: "var(--faint)" }}>&mdash;</span>}
                      </td>

                      <td style={{ padding: "12px 16px", textAlign: "right" }}>
                        <div style={{ display: "inline-flex", gap: "8px", alignItems: "center" }}>
                          <button
                            type="button"
                            className="btn"
                            onClick={() => handleOpenPreview(rep)}
                            style={{ padding: "5px 12px", fontSize: "12px" }}
                          >
                            Preview
                          </button>
                          <button
                            type="button"
                            className="btn ghost"
                            onClick={() => {
                              getReportById(rep.id).then((full) => {
                                if (full.report?.html) handleDownloadHtml(full.report);
                              });
                            }}
                            style={{ padding: "5px 10px", fontSize: "12px", display: "inline-flex", alignItems: "center", gap: "4px" }}
                            title="Download complete report HTML"
                          >
                            <IconDownload size={13} /> HTML
                          </button>
                          {canSend && (
                            <button
                              type="button"
                              className="btn primary"
                              onClick={() => onOpenApproval && onOpenApproval(act)}
                              style={{ padding: "5px 12px", fontSize: "12px", width: "auto" }}
                            >
                              Review &amp; send
                            </button>
                          )}
                        </div>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {/* Report Preview Modal */}
      {previewReport && (
        <div className="modal-backdrop" onClick={() => setPreviewReport(null)} role="dialog" aria-modal="true">
          <div
            className="approval-modal"
            onClick={(e) => e.stopPropagation()}
            style={{
              maxWidth: "880px",
              width: "92vw",
              height: "88vh",
              maxHeight: "860px",
              display: "flex",
              flexDirection: "column",
              padding: 0,
              background: "var(--panel)",
              border: "1px solid var(--border)",
              borderRadius: "14px",
              overflow: "hidden",
              boxShadow: "0 24px 60px rgba(0,0,0,0.65)",
            }}
          >
            {/* Modal Header */}
            <div
              style={{
                padding: "16px 20px",
                borderBottom: "1px solid var(--border)",
                display: "flex",
                alignItems: "center",
                justifyContent: "space-between",
                background: "var(--panel)",
              }}
            >
              <div>
                <h3 style={{ margin: 0, fontSize: "16px", fontWeight: 700, color: "var(--text)" }}>
                  {previewReport.subject}
                </h3>
                <div style={{ fontSize: "12px", color: "var(--muted)", marginTop: "2px" }}>
                  Snapshot: {previewReport.id} &middot; Created {formatReportDate(previewReport.created_at)}
                </div>
              </div>

              <div style={{ display: "flex", alignItems: "center", gap: "10px" }}>
                {previewReport.html && (
                  <button
                    type="button"
                    className="btn"
                    onClick={() => handleDownloadHtml(previewReport)}
                    style={{ padding: "5px 12px", fontSize: "12px", display: "flex", alignItems: "center", gap: "6px" }}
                  >
                    <IconDownload size={14} /> Download HTML
                  </button>
                )}
                {previewReport.attachment_csv && (
                  <button
                    type="button"
                    className="btn ghost"
                    onClick={() => {
                      const blob = new Blob([previewReport.attachment_csv], { type: "text/csv;charset=utf-8" });
                      const url = URL.createObjectURL(blob);
                      const link = document.createElement("a");
                      link.href = url;
                      link.download = `FinPilot_Attachment_${previewReport.id?.slice(0, 8) || "data"}.csv`;
                      document.body.appendChild(link);
                      link.click();
                      document.body.removeChild(link);
                    }}
                    style={{ padding: "5px 12px", fontSize: "12px", display: "flex", alignItems: "center", gap: "6px" }}
                  >
                    <IconDownload size={14} /> Download CSV
                  </button>
                )}
                <button
                  type="button"
                  onClick={() => setPreviewReport(null)}
                  aria-label="Close"
                  style={{
                    background: "none",
                    border: "none",
                    color: "var(--muted)",
                    cursor: "pointer",
                    padding: "4px",
                    display: "flex",
                  }}
                >
                  <IconX size={20} />
                </button>
              </div>
            </div>

            {/* Modal Iframe Content */}
            <div style={{ flex: 1, minHeight: 0, height: "100%", background: "#F3F5F8", position: "relative", overflow: "hidden" }}>
              {previewLoading ? (
                <div style={{ padding: "40px", textAlign: "center", color: "#5B6475", background: "#F3F5F8", height: "100%" }}>
                  Loading full report...
                </div>
              ) : previewReport.html ? (
                <iframe
                  title="Report Full Preview"
                  srcDoc={previewReport.html}
                  sandbox=""
                  style={{
                    position: "absolute",
                    top: 0,
                    left: 0,
                    width: "100%",
                    height: "100%",
                    border: "none",
                    display: "block",
                    background: "#F3F5F8",
                  }}
                />
              ) : (
                <div style={{ padding: "40px", textAlign: "center", color: "#5B6475", background: "#F3F5F8", height: "100%" }}>
                  HTML content not available.
                </div>
              )}
            </div>

            {/* Modal Footer */}
            <div
              style={{
                padding: "12px 20px",
                borderTop: "1px solid var(--border)",
                display: "flex",
                alignItems: "center",
                justifyContent: "space-between",
                background: "var(--panel-2)",
              }}
            >
              <div style={{ fontSize: "12px", color: "var(--faint)" }}>
                Rendered inside sandboxed iframe without scripts.
              </div>

              <div style={{ display: "flex", gap: "10px" }}>
                {actionsMap[previewReport.id] &&
                  (actionsMap[previewReport.id].status === "pending_approval" ||
                    actionsMap[previewReport.id].status === "failed") && (
                    <button
                      type="button"
                      className="btn primary"
                      onClick={() => {
                        const act = actionsMap[previewReport.id];
                        setPreviewReport(null);
                        if (onOpenApproval) onOpenApproval(act);
                      }}
                      style={{ width: "auto", fontSize: "12px", padding: "6px 16px" }}
                    >
                      Review &amp; approve send
                    </button>
                  )}
                <button type="button" className="btn" onClick={() => setPreviewReport(null)}>
                  Close
                </button>
              </div>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
